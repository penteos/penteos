import { spawn, spawnSync } from "node:child_process";
import { chmodSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import type * as Pty from "node-pty";

/**
 * Integrated terminal. A real bash in a pty, with wrappers for integrated
 * tools: before nmap runs, a hook asks the core whether its targets are in scope (and blocks it
 * if not); afterwards the XML output is ingested into the graph. Everything else works exactly
 * like a normal shell.
 */

export interface TerminalEnv {
  url: string;
  token: string;
  workDir: string;
  hookDir: string;
}

const HOOK = `// Generated by Penteos. Called by the shell wrappers of the integrated terminal.
const [, , phase, ...args] = process.argv;
const url = process.env.PENTEOS_URL;
const headers = { "content-type": "application/json", authorization: "Bearer " + process.env.PENTEOS_TOKEN };
const red = (s) => "\\x1b[38;5;174m" + s + "\\x1b[0m";
const green = (s) => "\\x1b[38;5;115m" + s + "\\x1b[0m";
const dim = (s) => "\\x1b[2m" + s + "\\x1b[0m";
try {
  if (phase === "pre") {
    const [tool, ...argv] = args;
    const res = await fetch(url + "/v0/terminal/pre", { method: "POST", headers, body: JSON.stringify({ tool, argv }) });
    const body = await res.json();
    if (body.decision !== "allow") {
      process.stderr.write(red("✗ Penteos blocked " + tool + ": ") + body.reason + "\\n");
      process.exit(1);
    }
    process.stderr.write(green("✔ in scope") + dim(" · " + body.targets.join(", ") + " · run " + body.runId.slice(-6)) + "\\n");
    process.stdout.write(body.runId);
  } else if (phase === "post") {
    const [runId, exitCode, xmlPath] = args;
    const res = await fetch(url + "/v0/terminal/post", { method: "POST", headers, body: JSON.stringify({ runId, exitCode: Number(exitCode), xmlPath }) });
    const body = await res.json();
    const s = body.summary;
    if (s) {
      const created = Object.entries(s.created ?? {}).map(([k, n]) => n + " " + k).join(", ") || "no new entities";
      process.stderr.write(green("✓ ingested: ") + created + dim(" · " + (s.edges ?? 0) + " relations") + "\\n");
    }
  }
} catch (error) {
  process.stderr.write(red("✗ Penteos does not answer: ") + error.message + "\\n");
  process.exit(phase === "pre" ? 1 : 0);
}
`;

const RC = `# Generated by Penteos
[ -f ~/.bashrc ] && source ~/.bashrc
# Penteos's own Node runs the hook; nothing else in this shell sees ELECTRON_RUN_AS_NODE (an Electron
# app opened from here - an editor, a chat - must start as itself).
__penteos_hook() { ELECTRON_RUN_AS_NODE=1 "$PENTEOS_NODE" "$PENTEOS_HOOK" "$@"; }
nmap() {
  local run_id
  run_id=$(__penteos_hook pre nmap "$@") || return 1
  command nmap "$@" -oX "$PENTEOS_WORK/$run_id.xml"
  local code=$?
  __penteos_hook post "$run_id" "$code" "$PENTEOS_WORK/$run_id.xml"
  return $code
}
export PS1="\\[\\e[38;5;141m\\]penteos\\[\\e[0m\\] \\[\\e[38;5;245m\\]\\w\\[\\e[0m\\] \\$ "
`;

/** One open terminal, whatever runs it. */
interface Term {
  write(data: string): void;
  resize(cols: number, rows: number): void;
  kill(): void;
}

/**
 * How terminals run on this machine: a real pty (node-pty), else `script` from util-linux (a real
 * terminal too, without resizing), else a plain shell. node-pty is loaded only when the first
 * terminal opens, so a machine where it cannot load still runs everything else.
 */
export type TerminalMode = "pty" | "script" | "pipe";

let ptyModule: typeof Pty | null | undefined;
function loadPty(): typeof Pty | null {
  if (ptyModule !== undefined) return ptyModule;
  try {
    const req = createRequire(import.meta.url);
    executableHelpers(dirname(req.resolve("node-pty/package.json")));
    ptyModule = req("node-pty") as typeof Pty;
  } catch (e) {
    process.stderr.write(`terminal: node-pty did not load (${(e as Error).message.split("\n")[0]}); using the fallback terminal\n`);
    ptyModule = null;
  }
  return ptyModule;
}

/**
 * node-pty starts shells through a small `spawn-helper` program (macOS). Package managers often
 * unpack it without the execute bit, and then every terminal fails with "posix_spawnp failed":
 * give it the bit back where it is missing (and the folder is ours to write).
 */
function executableHelpers(ptyDir: string): void {
  if (process.platform !== "darwin") return;
  const candidates = [join(ptyDir, "build", "Release", "spawn-helper"), join(ptyDir, "build", "Debug", "spawn-helper")];
  try {
    for (const d of readdirSync(join(ptyDir, "prebuilds"))) candidates.push(join(ptyDir, "prebuilds", d, "spawn-helper"));
  } catch {
    /* no prebuilds folder */
  }
  for (const file of candidates) {
    try {
      if (existsSync(file) && (statSync(file).mode & 0o111) === 0) chmodSync(file, 0o755);
    } catch {
      /* read-only install: nothing to do here */
    }
  }
}

const has = (cmd: string) => spawnSync("sh", ["-c", `command -v ${cmd}`], { stdio: "ignore" }).status === 0;

/** The shell: bash (the integration needs it), else the user's, else sh. */
function shellOf(): { cmd: string; args: (rc: string) => string[] } {
  if (has("bash")) return { cmd: "bash", args: (rc) => ["--rcfile", rc, "-i"] };
  const user = process.env.SHELL && existsSync(process.env.SHELL) ? process.env.SHELL : "/bin/sh";
  return { cmd: user, args: () => ["-i"] };
}

export class TerminalManager {
  private readonly terminals = new Map<string, Term>();
  private counter = 0;
  private readonly rcPath: string;
  private readonly hookPath: string;

  constructor(
    private readonly env: TerminalEnv,
    /** Tests: run in this mode whatever the machine has. */
    private readonly force?: TerminalMode,
  ) {
    mkdirSync(env.hookDir, { recursive: true });
    mkdirSync(env.workDir, { recursive: true });
    this.hookPath = join(env.hookDir, "hook.mjs");
    this.rcPath = join(env.hookDir, "bashrc");
    writeFileSync(this.hookPath, HOOK, { mode: 0o600 });
    writeFileSync(this.rcPath, RC, { mode: 0o600 });
    chmodSync(this.hookPath, 0o600);
  }

  /** How terminals run here (shown to the operator when it is not a full one). */
  get mode(): TerminalMode {
    if (this.force) return this.force;
    // `script` with these arguments is util-linux's; macOS ships the BSD one, with another syntax.
    return loadPty() ? "pty" : process.platform === "linux" && has("script") ? "script" : "pipe";
  }

  open(cols: number, rows: number, onData: (data: string) => void, onExit: (code: number) => void): string {
    const id = `t${++this.counter}`;
    const { ELECTRON_RUN_AS_NODE: _electronAsNode, ...inherited } = process.env as Record<string, string>;
    const env: Record<string, string> = {
      ...inherited,
      PENTEOS_URL: this.env.url,
      PENTEOS_TOKEN: this.env.token,
      PENTEOS_NODE: process.execPath,
      PENTEOS_HOOK: this.hookPath,
      PENTEOS_WORK: this.env.workDir,
      COLORTERM: "truecolor",
      TERM: "xterm-256color",
    };
    const cwd = process.env.HOME ?? "/";
    const shell = shellOf();
    const done = (code: number) => {
      if (!this.terminals.has(id)) return;
      this.terminals.delete(id);
      onExit(code);
    };
    const mode = this.mode;
    const pty = mode === "pty" ? loadPty() : null;
    let term: Term;
    if (pty) {
      const p = pty.spawn(shell.cmd, shell.args(this.rcPath), { name: "xterm-256color", cols, rows, cwd, env });
      p.onData(onData);
      p.onExit(({ exitCode }) => done(exitCode));
      term = { write: (d) => p.write(d), resize: (c, r) => p.resize(c, r), kill: () => p.kill() };
    } else {
      // `script` gives the shell a real terminal; the size is set once, at the start.
      const inner = [shell.cmd, ...shell.args(this.rcPath)].map((a) => `'${a.replace(/'/g, "'\\''")}'`).join(" ");
      const child = mode === "script"
        ? spawn("script", ["-qfec", `stty cols ${cols} rows ${rows} 2>/dev/null; exec ${inner}`, "/dev/null"], { cwd, env, stdio: ["pipe", "pipe", "pipe"] })
        : spawn(shell.cmd, shell.args(this.rcPath), { cwd, env: { ...env, COLUMNS: String(cols), LINES: String(rows) }, stdio: ["pipe", "pipe", "pipe"] });
      child.stdout.on("data", (d: Buffer) => onData(d.toString("utf8")));
      child.stderr.on("data", (d: Buffer) => onData(d.toString("utf8")));
      child.on("exit", (code) => done(code ?? 0));
      child.on("error", () => done(1));
      term = { write: (d) => child.stdin.write(d), resize: () => {}, kill: () => child.kill("SIGHUP") };
    }
    this.terminals.set(id, term);
    // Not a full terminal: said once, in the terminal itself, instead of looking broken.
    if (mode !== "pty") {
      const why = mode === "script" ? "basic terminal: it does not fit the window size" : "minimal terminal: no colours or line editing";
      onData(`\x1b[2m(${why}; the terminal module did not load on this system)\x1b[0m\r\n`);
    }
    return id;
  }

  write(id: string, data: string): void {
    this.terminals.get(id)?.write(data);
  }

  resize(id: string, cols: number, rows: number): void {
    this.terminals.get(id)?.resize(Math.max(cols, 2), Math.max(rows, 1));
  }

  close(id: string): void {
    this.terminals.get(id)?.kill();
    this.terminals.delete(id);
  }

  closeAll(): void {
    for (const t of this.terminals.values()) t.kill();
    this.terminals.clear();
  }
}
