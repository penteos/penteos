export function msg(lang: Language, key: string, params: Params = {}): string {
  const text = (lang === "en" ? EN : ES)[key] ?? ES[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

